# ============================================================
# Block 2: Normalization
# ============================================================
# Normalizes expression data using the method specified in
# the config. For Affymetrix arrays, applies RMA via the affy
# or oligo package. For Illumina arrays, applies neqc via
# limma. For RNA-seq, aligns with STAR or pseudo-aligns with
# Salmon, counts with featureCounts, then applies vst (DESeq2)
# or TMM+voom (edgeR+limma). Pins the Ensembl release from
# the config for gene annotation consistency across all runs.
#
# Packages: affy, oligo, limma, DESeq2, edgeR, biomaRt
# External: STAR or Salmon, Subread (featureCounts)
# ============================================================

source("scripts/phase_a/00_load_config.R")

library(biomaRt)

# Pin Ensembl release from config
ensembl <- useEnsembl(
  biomart = "genes",
  dataset = "hsapiens_gene_ensembl",
  version = cfg$phase_a$ensembl_release
)

norm_method <- cfg$phase_a$normalization_method

if (norm_method == "RMA") {
  library(affy)
  # Load .CEL files, apply RMA
  # cel_files <- list.celfiles(file.path(run_dir, "raw"), full.names = TRUE)
  # raw <- ReadAffy(filenames = cel_files)
  # eset <- rma(raw)
  cat("RMA normalization selected.\n")

} else if (norm_method == "neqc") {
  library(limma)
  cat("neqc normalization selected.\n")

} else if (norm_method == "vst") {
  library(DESeq2)
  # Assumes count matrix already generated by featureCounts
  # counts <- read.csv(file.path(run_dir, "counts.csv"), row.names = 1)
  # dds <- DESeqDataSetFromMatrix(countData = counts, colData = coldata, design = ~ condition)
  # vsd <- vst(dds, blind = FALSE)
  cat("vst normalization (DESeq2) selected.\n")

} else if (norm_method == "TMM_voom") {
  library(edgeR)
  library(limma)
  cat("TMM + voom normalization selected.\n")
}

cat("Normalization step configured. Ensembl release:", cfg$phase_a$ensembl_release, "\n")
